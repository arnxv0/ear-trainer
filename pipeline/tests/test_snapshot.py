"""Regression snapshot of 20 real songs (keys, chords, numerals, functions, melody, timing).

The songs cover every main mode, secondary and borrowed chords, harmonic-minor
V, slash chords, extensions, a key change and an odd meter. Their expected
output was generated by the pipeline itself, so this guards against
regressions; it is only a ground truth once each song is checked by ear and its
`checked_by_ear` flag in fixtures/snapshot_entries.json.gz is set to true.

Regenerate after an intended change:  UPDATE_SNAPSHOTS=1 python -m unittest pipeline.tests.test_snapshot
"""

import gzip
import json
import os
import unittest
from pathlib import Path

from pipeline.build_corpus import build_segment
from pipeline.tests.test_build import new_stats

FIXTURES = Path(__file__).resolve().parent / "fixtures"
ENTRIES = FIXTURES / "snapshot_entries.json.gz"
EXPECTED = FIXTURES / "snapshot_expected.json.gz"
# Corpus-wide fields (they depend on every other song) are not part of the snapshot.
VOLATILE = ("tags", "difficulty", "yt_ok")


def build_all():
    entries = json.load(gzip.open(ENTRIES))
    out = {}
    for hid, fx in sorted(entries.items()):
        seg = build_segment(hid, fx["entry"], fx["raw"], new_stats())
        out[hid] = {k: v for k, v in seg.items() if k not in VOLATILE}
    return entries, out


class SnapshotTest(unittest.TestCase):
    def test_twenty_songs_match_snapshot(self):
        entries, built = build_all()
        self.assertEqual(len(entries), 20)
        if os.environ.get("UPDATE_SNAPSHOTS"):
            with gzip.open(EXPECTED, "wt") as f:
                json.dump(built, f, indent=1, ensure_ascii=False)
            self.skipTest("snapshot regenerated")
        expected = json.load(gzip.open(EXPECTED))
        self.assertEqual(sorted(built), sorted(expected))
        for hid in expected:
            with self.subTest(song=hid, why=entries[hid]["why"]):
                self.assertEqual(json.loads(json.dumps(built[hid])), expected[hid])


if __name__ == "__main__":
    unittest.main()
